// One-off: vectorize her wordmark letters and WB badge into SVG path data.
// Usage: node scripts/trace-brand.mjs <dir-with-letter-pngs> <out.js>
import potrace from 'potrace';
import { writeFileSync } from 'node:fs';
const [dir, out] = process.argv.slice(2);
const trace = (file) => new Promise((res, rej) => {
  const p = new potrace.Potrace({ turdSize: 60, optTolerance: 2.2, alphaMax: 1.25, threshold: 128 });
  p.loadImage(file, (err) => err ? rej(err) : res(p.getPathTag().match(/ d="([^"]+)"/)[1].replace(/-?\d+\.\d+/g, (n) => String(Math.round(+n))).replace(/\s+/g, ' ').trim()));
});
// positions from the 1325x363 source wordmark (x, y, w, h), traced at 3x
const boxes = [[27,26,289,240],[297,115,133,143],[432,114,132,143],[567,38,140,220],[713,30,172,229],[888,114,139,141],[1025,41,121,214],[1149,117,119,184]];
const chars = 'WoodBaby';
const letters = [];
for (let i = 0; i < 8; i++) {
  const d = await trace(`${dir}/letter_${i}.png`);
  const [x, y, w, h] = boxes[i];
  letters.push({ char: chars[i], x, y, w, h, vb: `0 0 ${w * 3} ${h * 3}`, d });
}
const badge = {};
for (const k of ['shadow', 'outline', 'fill']) badge[k] = await trace(`${dir}/logo_${k}.png`);
const src = `// Generated by scripts/trace-brand.mjs from her wordmark and WB badge artwork.\n` +
  `export const WORDMARK = { width: 1325, height: 363, scale: 3, letters: ${JSON.stringify(letters)} };\n` +
  `export const BADGE = { viewBox: '0 0 1932 1212', layers: ${JSON.stringify(badge)} };\n`;
writeFileSync(out, src);
console.log('letters', letters.map(l => l.char + ':' + l.d.length).join(' '), 'badge', Object.values(badge).map(d => d.length));
